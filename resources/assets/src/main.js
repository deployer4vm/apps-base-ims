import Vue from "vue";
import App from "./App";
import router from "./router";
import { store } from "./store/store";

import BootstrapVue from "bootstrap-vue";

import globals from "./globals";
import Popper from "popper.js";
import { UserAuth, AppTemplate } from "./helper";

// import { resolve } from 'dns';

// Required to enable animations on dropdowns/tooltips/popovers
Popper.Defaults.modifiers.computeStyle.gpuAcceleration = false;

Vue.config.productionTip = false;

Vue.use(BootstrapVue);

//register all project Modules vue component
const moduleVueComponents = require.context(
    "../../../app/MainApp/Modules",
    true,
    /components*\.vue$/i
);
moduleVueComponents.keys().forEach(key =>
    Vue.component(
        key
            .split("/")
            .pop()
            .split(".")[0],
        moduleVueComponents(key).default
    )
);

//register project global vue component
const projectVueComponents = require.context(
    "../../../app/MainApp/resources/js/components",
    true,
    /\.vue$/i
);
projectVueComponents.keys().forEach(key =>
    Vue.component(
        key
            .split("/")
            .pop()
            .split(".")[0],
        projectVueComponents(key).default
    )
);

// load project main.js init
require("../../../app/MainApp/resources/js/main");

// load all module main.js init listed on modules.js, this file is autogenerated
require("../../../app/MainApp/resources/js/modules");

// Global RTL flag
window.Vue.mixin({
    data: globals
});

new Vue({
    router,
    store,
    created() {
        //init helper UserAuth
        window.UserAuth = UserAuth;
        window.UserAuth.store = this.$store;
        //init helper app template
        window.AppTemplate = AppTemplate;
        window.AppTemplate.store = this.$store;
        window.AppTemplate.router = this.$router;
    },
    render: h => h(App)
}).$mount("#app");
